    def teardown_method(self):
        """Clean up after each test."""
        # Remove temporary directory
        shutil.rmtree(self.temp_dir, ignore_errors=True)
    
    def create_test_files(self):
        """Create test markdown files for testing."""
        # File 1: Has content but no summary in database
        (self.base_path / "file1.md").write_text("# Test File 1\n\nThis is test content for file 1.")
        
        # File 2: Has content and will be in database
        (self.base_path / "file2.md").write_text("# Test File 2\n\nThis is test content for file 2.")
        
        # File 3: Has content but will be modified
        (self.base_path / "file3.md").write_text("# Test File 3\n\nThis is test content for file 3.")
        
        # Create a subdirectory with files
        subdir = self.base_path / "subdir"
        subdir.mkdir()
        (subdir / "file4.md").write_text("# Test File 4\n\nThis is test content in subdirectory.")
    
    def create_partial_database(self):
        """Create a database with some files but not all."""
        db = KnowledgeDatabase(str(self.db_path))
        
        # Add file2 to database
        file2_path = self.base_path / "file2.md"
        db.add_file(
            file_path=file2_path,
            summary="Existing summary for file 2",
            content_length=50
        )
        
        # Add file3 to database but with old hash (simulating file change)
        file3_path = self.base_path / "file3.md"
        db.add_file(
            file_path=file3_path,
            summary="Old summary for file 3",
            content_length=50
        )
        # Manually modify the hash to simulate file change
        file3_key = str(file3_path.resolve())
        db.db_data["files"][file3_key]["metadata"]["file_hash"] = "old_hash"
        
        db.save_database()
        return db
    
