    @patch('knowledge_base_builder.QuestionAnswerer')
    @patch('knowledge_base_builder.SemanticSearchV2')
    @patch('knowledge_base_builder.MarkdownSummarizerV2')
    def test_validate_summaries(self, mock_summarizer_class, mock_semantic_class, mock_qa_class):
        """Test summary validation functionality."""
        # Create a database with various scenarios
        db = KnowledgeDatabase(str(self.db_path))
        
        # Add file with good summary
        file1_path = self.base_path / "file1.md"
        db.add_file(
            file_path=file1_path,
            summary="This is a good quality summary with appropriate length for testing validation.",
            content_length=100
        )
        
        # Add file with short summary
        file2_path = self.base_path / "file2.md"
        db.add_file(
            file_path=file2_path,
            summary="Short",  # Too short
            content_length=100
        )
        
        # Add file with long summary
        file3_path = self.base_path / "file3.md"
        long_summary = "This is an extremely long summary that exceeds the recommended length for summaries in our knowledge base system. " * 10
        db.add_file(
            file_path=file3_path,
            summary=long_summary,
            content_length=100
        )
        
        # Add orphaned entry (file doesn't exist)
        orphaned_path = self.base_path / "nonexistent.md"
        db.add_file(
            file_path=orphaned_path,
            summary="Summary for non-existent file",
            content_length=100
        )
        
        db.save_database()
        
        # Create knowledge base builder
        builder = KnowledgeBaseBuilder(
            base_directory=str(self.base_path),
            db_path=str(self.db_path),
            embeddings_cache_path=str(self.cache_path)
        )
        
        # Test validation
        result = builder.validate_summaries()
        
        # Verify validation results
        assert result["total_files"] == 4  # Including orphaned entry
        assert result["files_with_summaries"] >= 3
        assert result["files_with_short_summaries"] >= 1
        assert result["files_with_long_summaries"] >= 1
        assert result["orphaned_database_entries"] >= 1
        assert len(result["consistency_issues"]) >= 3

    def test_knowledge_database_new_methods(self):
        """Test new methods added to KnowledgeDatabase."""
        db = KnowledgeDatabase(str(self.db_path))
        
        # Test has_file method
        file_path = self.base_path / "file1.md"
        file_key = str(file_path.resolve())
        
        assert not db.has_file(file_key)  # File not in database yet
        
        # Add file
        db.add_file(file_path, "Test summary", 100)
        
        assert db.has_file(file_key)  # File now in database
        
        # Test get_file_data method
        file_data = db.get_file_data(file_key)
        assert file_data is not None
        assert file_data["summary"] == "Test summary"
        
        # Test get_all_files_dict method
        all_files = db.get_all_files_dict()
        assert isinstance(all_files, dict)
        assert file_key in all_files


